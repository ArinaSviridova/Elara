export default function InfoTooltip({ id, label, style }) {
  const [open, setOpen] = useState(false)
  const info = TOOLTIPS[id]

  if (!info) return null

  return (
    <span style={{ position:'relative', display:'inline-flex', alignItems:'center', ...style }}>
      <span role="button" tabIndex={0}
        onClick={e => { e.stopPropagation(); setOpen(o => !o) }}
        onKeyDown={e => e.key==='Enter'&&setOpen(o=>!o)}
        style={{
          width:16, height:16, borderRadius:'50%', background:'var(--bg3)',
          border:'1px solid var(--border)', color:'var(--text3)', fontSize:10,
          cursor:'pointer', display:'inline-flex', alignItems:'center', justifyContent:'center',
          fontWeight:600, padding:0, marginLeft:4, flexShrink:0, lineHeight:1,
          userSelect:'none',
        }}
        aria-label={`Подробнее о ${label || id}`}
      >?</span>

      {open && (
        <>
          <div onClick={e => { e.stopPropagation(); setOpen(false) }}
            style={{ position:'fixed', inset:0, zIndex:99 }} />
          <div style={{
            position:'fixed', bottom:80, left:16, right:16,
            zIndex:100, background:'var(--bg2)', border:'1px solid var(--border)',
            borderRadius:12, padding:'14px 16px',
            boxShadow:'0 8px 32px rgba(0,0,0,0.4)',
          }}>
            {label && <div style={{ fontSize:13, fontWeight:500, color:'var(--text)', marginBottom:8 }}>{label}</div>}
            <p style={{ fontSize:13, color:'var(--text2)', lineHeight:1.6, margin:0 }}>{info.ru}</p>
            {info.ref && (
              <div style={{ fontSize:11, color:'var(--accent)', marginTop:8 }}>📚 {info.ref}</div>
            )}
            <span role="button" tabIndex={0} onClick={() => setOpen(false)} onKeyDown={e=>e.key==='Enter'&&setOpen(false)} style={{
              display:'inline-block', marginTop:10, background:'none', border:'1px solid var(--border)',
              borderRadius:6, color:'var(--text3)', fontSize:11, padding:'4px 12px', cursor:'pointer',
            }}>Закрыть</span>
          </div>
        </>
      )}
    </span>
  )
}
